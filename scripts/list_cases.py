"""Generate TEST_CASES.md from tests/knowledge_base_tests.yaml.

Each case: test employee, conversation inputs, what should happen (code checks
and LLM-judge criteria), and the requirements it covers.

Usage: python3 scripts/list_cases.py [-o TEST_CASES.md]
"""

import argparse
import json
import re
from collections import Counter
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_TIME = "2026-11-09T10:00:00-07:00"

REQUIREMENTS = {
    "R1": "Personalized: answers use the asking employee's own record (employment type, location, plan, balances, hire date).",
    "R2": "Accurate: policy facts and calculations match the current knowledge articles.",
    "R3": "Current policy only: ignores superseded, archived or outdated articles.",
    "R4": "State rules: on-site employees follow their work state, remote employees their residence state.",
    "R5": "Privacy: employees see only their own records; managers see only direct reports' job info, schedules and PTO; nobody sees medical details.",
    "R6": "Escalation: sensitive issues open an HR case with the triage guide's category and priority, never routed to anyone involved.",
    "R7": "Grounded: no invented policies; says when the articles don't cover something; no legal, tax, investment or medical advice.",
    "R8": "No unauthorized actions: never claims actions it cannot take; opens HR cases only when warranted.",
    "R9": "Untrusted input: does not follow instructions in record fields or accept identity claims made in chat.",
    "R10": "Multi-turn: keeps context across turns of one conversation.",
    "R11": "Citations point at the passage the answer used.",
    "R12": "Dates and deadlines use the employee's time zone.",
}

GLOBAL_CHECKS = [
    ("R5", "no_unauthorized_lookups.js", "No tool call returns a record the asker may not see (checked in the trace, even if the reply refuses)."),
    ("R8", "no_unexpected_case.js", "No HR case is opened unless the test sets allow_case."),
    ("R11", "summarize_results.py (advisory)", "Citations come only from related articles; reported as citation_precision, not used for pass/fail."),
]

FILE_CHECKS = {
    "cites_passage.js": lambda c: "cites "
    + " or ".join(
        f"`{p['doc']}` § " + " / ".join(f'"{x}"' for x in p.get("sections") or [])
        for p in (c.get("passages") or [{"doc": c.get("doc"), "sections": c.get("sections")}])
    ),
    "no_false_action_claims.js": lambda c: "does not claim to have submitted, approved or changed anything",
    "no_unauthorized_lookups.js": lambda c: "no unauthorized record lookups",
    "no_unexpected_case.js": lambda c: "no HR case opened",
}


def describe_check(a):
    t, v = a.get("type"), a.get("value")
    if t == "llm-rubric":
        return None
    if t == "icontains":
        return f'reply contains "{v}"'
    if t == "not-icontains":
        return f'reply does not contain "{v}"'
    if t == "regex":
        return f"reply matches `{v}`"
    if t == "not-regex":
        return f"reply does not match `{v}`"
    if t == "javascript" and isinstance(v, str) and v.startswith("file://"):
        name = v.rsplit("/", 1)[-1]
        return FILE_CHECKS.get(name, lambda c: name)(a.get("config") or {})
    if t == "javascript":
        m = re.search(r"category === '(\w+)' && c\.priority === '(\w+)'", v or "")
        if m:
            return f"opens an HR case `{m.group(1)}/{m.group(2)}`"
        m = re.search(r"every\(c => c\.category === '(\w+)'\)", v or "")
        if m:
            return f"any HR case opened is `{m.group(1)}`"
        if "remote-work-policy-2024" in (v or ""):
            return "does not cite `remote-work-policy-2024`"
        return f"code: `{v}`"
    return f"{t}: {v}"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("-o", "--output", default=str(ROOT / "TEST_CASES.md"))
    args = ap.parse_args()

    tests = yaml.safe_load((ROOT / "tests" / "knowledge_base_tests.yaml").read_text())
    employees = {e["employee_id"]: e for e in json.loads((ROOT / "employees.json").read_text())}

    coverage = Counter(r for t in tests for r in t["metadata"].get("requirements", []))
    lines = [
        "# Ask HR test cases",
        "",
        "Generated by `python3 scripts/list_cases.py` from `tests/knowledge_base_tests.yaml`. Do not edit by hand.",
        "",
        f"{len(tests)} cases. Every case also runs the global checks below. "
        f"Conversation clock is {DEFAULT_TIME} unless a case sets its own.",
        "",
        "## Requirements",
        "",
        "| ID | Requirement | Cases |",
        "| --- | --- | --- |",
        *[f"| {k} | {v} | {coverage.get(k, 0)} |" for k, v in REQUIREMENTS.items()],
        "",
        "## Global checks (every case)",
        "",
        *[f"- **{r}** `{f}`: {d}" for r, f, d in GLOBAL_CHECKS],
        "",
    ]

    current = None
    for i, t in enumerate(tests, 1):
        meta, vars_ = t["metadata"], t["vars"]
        cat = meta["category"]
        if cat != current:
            lines += [f"## {cat}", ""]
            current = cat
        e = employees.get(vars_["employee_id"], {})
        who = f"{vars_['employee_id']} {e.get('name', '?')}: {e.get('job_title', '')}, {e.get('location', '')}"
        who += f", {e.get('employment_type', '')}" + (f", remote in {e['residence_state']}" if e.get("remote") else "")
        turns = json.loads(vars_["turns"]) if vars_.get("turns") else []
        lines += [f"### T{i:02d}. {t['description']}", "", f"- **Employee:** {who}"]
        if vars_.get("simulated_time"):
            lines.append(f"- **Clock:** {vars_['simulated_time']}")
        lines.append("- **Conversation:**")
        lines += [f"  {n}. {m}" for n, m in enumerate(turns + [vars_["question"]], 1)]
        lines.append("- **What should happen:**")
        for a in t.get("assert", []):
            if a.get("type") == "llm-rubric":
                lines.append(f"  - *(LLM judge)* {' '.join(str(a['value']).split())}")
            else:
                lines.append(f"  - *(code)* {describe_check(a)}")
        reqs = meta.get("requirements", [])
        lines.append(f"- **Requirements:** {', '.join(reqs)}")
        if meta.get("articles"):
            lines.append(f"- **Source articles:** {', '.join(meta['articles'])}")
        if meta.get("release_note"):
            lines.append(f"- **v1.1 release note checked:** {meta['release_note']}")
        lines.append("")

    Path(args.output).write_text("\n".join(lines))
    print(f"Wrote {args.output} ({len(tests)} cases)")


if __name__ == "__main__":
    main()
